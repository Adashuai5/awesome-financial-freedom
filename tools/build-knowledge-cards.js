// 从 knowledge/nodes/*.json 自动生成 demo/calculators/knowledge-data.js
// 避免 demo 内嵌副本与源节点漂移。
// 使用：node tools/build-knowledge-cards.js
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const nodesDir = path.join(repoRoot, 'knowledge/nodes');
const outFile = path.join(repoRoot, 'demo/calculators/knowledge-data.js');

// demo 真正需要的节点（与 pickRelevantCards 选择器对齐）
const NEEDED_IDS = [
  'four-percent-rule',
  'fire-types',
  'emergency-fund',
  'housing-fund-optimization',
  'dual-wheel-allocation',
  'savings-rate',
];

function walkJSON(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walkJSON(full));
    else if (entry.name.endsWith('.json')) out.push(full);
  }
  return out;
}

const nodes = {};
for (const file of walkJSON(nodesDir)) {
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!NEEDED_IDS.includes(data.id)) continue;
  // 只挑出 demo 需要的字段，节省体积
  nodes[data.id] = {
    title: data.title,
    summary: data.answer?.summary || '',
    limitations: data.answer?.limitations || data.answer?.optimization_strategies?.slice(0, 3) || [],
    href: path.relative(path.dirname(outFile), file).replace(/\\/g, '/'),
  };
}

const missing = NEEDED_IDS.filter(id => !nodes[id]);
if (missing.length) {
  console.error('Missing nodes:', missing.join(', '));
  process.exit(1);
}

const banner = `// AUTO-GENERATED by tools/build-knowledge-cards.js — do not edit by hand.
// Source: knowledge/nodes/*.json. Regenerate with: npm run build:knowledge-cards\n`;
const body = `export const KNOWLEDGE_CARDS = ${JSON.stringify(nodes, null, 2)};\n`;
fs.writeFileSync(outFile, banner + body);
console.log(`Wrote ${outFile} with ${Object.keys(nodes).length} cards.`);
